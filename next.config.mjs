/** @type {import('next').NextConfig} */

/*
 * Content-Security-Policy is NOT set here.
 * It is set per-request in middleware.ts using a cryptographic nonce so
 * Next.js Turbopack's inline hydration scripts can be allowed without
 * 'unsafe-inline'. Static headers cannot contain a nonce (no request
 * context), so the CSP must live in middleware.
 */
const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
]

const nextConfig = {
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
    ]
  },
  images: {
    remotePatterns: [
      {
        protocol: "https",
        hostname: "cdn.sanity.io",
      },
      {
        protocol: "https",
        hostname: "images.unsplash.com",
      },
      {
        protocol: "https",
        hostname: "plus.unsplash.com",
      },
    ],
  },
  experimental: {
    scrollRestoration: false,
  },
}

export default nextConfig
